/// Remove and deserialize a required argument by snake_case name.
fn take_arg<T: DeserializeOwned>(args: &mut Value, name: &str) -> Result<T, String> {
    let obj = args.as_object_mut().ok_or_else(|| "args must be a JSON object".to_string())?;
    let value = obj.remove(name).ok_or_else(|| format!("missing argument `{name}`"))?;
    serde_json::from_value(value).map_err(|e| format!("argument `{name}`: {e}"))
}

/// Remove and deserialize an optional argument; absent or null yields `None`.
fn take_arg_opt<T: DeserializeOwned>(args: &mut Value, name: &str) -> Result<Option<T>, String> {
    let obj = args.as_object_mut().ok_or_else(|| "args must be a JSON object".to_string())?;
    match obj.remove(name) {
        None | Some(Value::Null) => Ok(None),
        Some(value) => serde_json::from_value(value).map(Some)
            .map_err(|e| format!("argument `{name}`: {e}")),
    }
}

fn to_value<T: serde::Serialize>(v: T) -> Result<Value, String> {
    serde_json::to_value(v).map_err(|e| format!("serialize result: {e}"))
}

