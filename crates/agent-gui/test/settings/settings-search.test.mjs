const cratesRoot = fileURLToPath(new URL("../../../", import.meta.url));
const loader = createTsModuleLoader();
const {
  SETTINGS_SEARCH_INDEX,
  SETTINGS_SEARCH_SECTION_LABEL_KEYS,
  searchSettingsIndex,
} = loader.loadModule("@liveagent/ui/lib/settings/settingsSearchIndex.ts");
const { SHORTCUT_COMMANDS } = loader.loadModule("@liveagent/ui/lib/shortcuts/shortcutCommands.ts");
const webLoader = createTsModuleLoader({ rootDir: path.join(cratesRoot, "agent-gateway/web") });
const guiTranslations = loader.loadModule("src/i18n/config.ts").translations;
const webTranslations = webLoader.loadModule("src/i18n/config.ts").translations;
const { desktopSettingsSearch } = loader.loadModule("src/agent-ui-adapters/settingsSearch.ts");
const { webSettingsSearch } = webLoader.loadModule("src/agent-ui-adapters/settingsSearch.ts");
// [host, translations, index the host searches, section labels it shows]
const hosts = [
  ["desktop", guiTranslations, desktopSettingsSearch],
  ["web", webTranslations, webSettingsSearch],
].map(([host, translations, extension]) => ({
  host,
  translations,
  entries: [...SETTINGS_SEARCH_INDEX, ...extension.entries],
  sectionLabelKeys: { ...SETTINGS_SEARCH_SECTION_LABEL_KEYS, ...extension.sectionLabelKeys },
}));
const allEntries = [
  ...SETTINGS_SEARCH_INDEX,
  ...desktopSettingsSearch.entries,
  ...webSettingsSearch.entries,
];

const read = (relative) => fs.readFileSync(path.join(cratesRoot, relative), "utf8");

function sourceFiles(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) return sourceFiles(absolute);
    return /\.tsx?$/.test(entry.name) ? [absolute] : [];
  });
}

// Every section a settings page can render, read from the section tables.
function renderedSectionIds() {
  const ids = new Set();
  const collect = (source) => {
    for (const match of source.matchAll(/^\s+id: "([\w-]+)",$/gm)) ids.add(match[1]);
  };
  collect(read("agent-ui/src/pages/settings/SettingsPage.tsx"));
  collect(read("agent-gui/src/agent-ui-adapters/settingsExtension.tsx"));
  collect(read("agent-gateway/web/src/agent-ui-adapters/settingsExtension.tsx"));
  // Generated by `(["skills", "mcp"] as const).map(...)`.
  assert.match(read("agent-ui/src/pages/settings/SettingsPage.tsx"), /\["skills", "mcp"\] as const/);
  ids.add("skills");
  ids.add("mcp");
  return ids;
}

test("every settings section contributes searchable entries", () => {
  const sections = renderedSectionIds();
  assert.ok(sections.size >= 20, `found ${sections.size} sections`);
  for (const section of sections) {
    const entries = allEntries.filter((entry) => entry.section === section);
    assert.ok(entries.length > 0, `section "${section}" has no settings search entries`);
    assert.ok(
      hosts.some(({ sectionLabelKeys }) => sectionLabelKeys[section]),
      `section "${section}" has no label`,
    );
  }
  for (const entry of allEntries) {
    assert.ok(sections.has(entry.section), `${entry.anchor} points at unknown section ${entry.section}`);
  }
  const shortcutEntries = SETTINGS_SEARCH_INDEX.filter((entry) => entry.anchor.startsWith("shortcut-"));
  assert.equal(shortcutEntries.length, SHORTCUT_COMMANDS.length, "each shortcut command is searchable");
});

test("index entries are unique, translated and anchored in a real settings row", () => {
  const anchors = allEntries.map((entry) => entry.anchor);
  assert.equal(new Set(anchors).size, anchors.length, "anchors are unique");

  for (const { host, translations, entries, sectionLabelKeys } of hosts) {
    const keys = [
      ...Object.values(sectionLabelKeys),
      ...entries.flatMap((entry) => [entry.labelKey, entry.descriptionKey].filter(Boolean)),
    ];
    for (const key of keys) {
      for (const locale of ["zh-CN", "en-US"]) {
        assert.ok(translations[locale][key], `${host} ${locale} misses ${key}`);
      }
    }
  }

  const sources = [
    ...sourceFiles(path.join(cratesRoot, "agent-ui/src")),
    ...sourceFiles(path.join(cratesRoot, "agent-gui/src")),
    ...sourceFiles(path.join(cratesRoot, "agent-gateway/web/src")),
  ]
    .map((file) => fs.readFileSync(file, "utf8"))
    .join("\n");
  for (const entry of allEntries) {
    if (entry.anchor.startsWith("shortcut-")) continue;
    const literal = new RegExp(
      `data-settings-anchor="${entry.anchor}"|settingsAnchor=\\{[^}]*"${entry.anchor}"`,
    );
    assert.match(sources, literal, `no element renders anchor "${entry.anchor}"`);
  }
  assert.match(
    read("agent-ui/src/pages/settings/ShortcutCommandsSection.tsx"),
    /data-settings-anchor=\{shortcutCommandSettingsAnchor\(command\.id\)\}/,
  );
});

const en = (key) => guiTranslations["en-US"][key] ?? key;
const zh = (key) => guiTranslations["zh-CN"][key] ?? key;
const [desktop] = hosts;
const allSections = Object.entries(desktop.sectionLabelKeys).map(([id, labelKey]) => ({
  id,
  labelKey,
}));

test("search ranks label hits first and honours the host's sections and rows", () => {
  const theme = searchSettingsIndex("theme", { t: en, sections: allSections });
  // "Switch theme" (a shortcut command) is a label hit; the appearance row
  // is found through its keywords right behind it.
  const appearance = theme.findIndex((result) => result.entry.anchor === "appearance");
  assert.ok(appearance >= 0 && appearance < 3, "keywords find the theme row");
  assert.equal(theme[appearance].sectionLabel, en("settings.navSystem"));

  const proxy = searchSettingsIndex("proxy", { t: en, sections: allSections });
  assert.equal(proxy[0].entry.anchor, "system-proxy");

  const notifications = (entries) =>
    searchSettingsIndex("notification", { t: en, sections: allSections, entries }).map(
      (result) => result.entry.anchor,
    );
  assert.ok(notifications(desktop.entries).includes("run-notifications"));
  assert.ok(!notifications(undefined).includes("run-notifications"), "host rows are opt-in");

  const onlySystem = searchSettingsIndex("search", {
    t: en,
    sections: [{ id: "system", labelKey: "settings.navSystem" }],
  });
  assert.ok(onlySystem.every((result) => result.entry.section === "system"));

  const chinese = searchSettingsIndex(zh("settings.language"), { t: zh, sections: allSections });
  assert.equal(chinese[0].entry.anchor, "language", "localized labels are searchable");
  assert.equal(
    searchSettingsIndex("language font", { t: en, sections: allSections }).length,
    0,
    "every token must match",
  );
  assert.deepEqual(searchSettingsIndex("   ", { t: en, sections: allSections }), []);
});

test("palette lists individual settings that open the section at the row", () => {
  const { buildCommandPaletteActions } = loader.loadModule(
    "@liveagent/ui/lib/chat/commandPaletteActions.ts",
  );
  const navigation = loader.loadModule("@liveagent/ui/lib/settings/settingsSearchNavigation.ts");
  const opened = [];
  const build = (settingsSearch) =>
    buildCommandPaletteActions({
      t: en,
      isMac: true,
      onOpenSettings: (section) => opened.push([section, navigation.takeSettingsAnchor()]),
      settingsSearch,
    }).filter((action) => action.id.startsWith("setting:"));

  assert.deepEqual(build(undefined), []);
  const desktopActions = build({ host: desktopSettingsSearch });
  const appearance = desktopActions.find((action) => action.id === "setting:appearance");
  assert.equal(appearance.label, `${en("settings.navSystem")}: ${en("settings.appearance")}`);
  assert.equal(appearance.searchOnly, true);
  assert.ok(appearance.keywords.includes("theme"));
  appearance.run();
  assert.deepEqual(opened, [["system", { section: "system", anchor: "appearance" }]]);

  assert.ok(desktopActions.some((action) => action.id === "setting:about-update"));
  const about = desktopActions.find((action) => action.id === "setting:about-update");
  assert.equal(about.label, `${en("settings.navAbout")}: ${en("settings.aboutSoftwareUpdate")}`);
  const web = build({ host: webSettingsSearch, hiddenSections: ["remote"] }).map((action) => action.id);
  assert.ok(web.includes("setting:devices"));
  assert.ok(!web.includes("setting:about-update"));
  assert.ok(!web.some((id) => id.startsWith("setting:remote-")));
  assert.ok(desktopActions.every((action) => action.id !== "setting:devices"));
});

